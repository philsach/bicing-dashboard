#!/bin/bash
# Weekly Bicing data update for macOS (run by launchd; see install_schedule.sh).
#
# Works in its own git worktree (.update-worktree/, ignored by git) so it never
# touches whatever you have checked out. Each run:
#   1. resets the worktree to the latest origin/main
#   2. runs `scripts/bicing_data.py update` (downloads what's missing over your
#      own connection, summarizes, rebuilds the last 3 complete months)
#   3. if data changed: commits to a branch named after the months, pushes it
#      and opens a pull request (with the GitHub CLI `gh`, if installed)
#   4. shows a macOS notification with the result
# Running it by hand is fine too:  scripts/macos/weekly_update.sh
# Set DRY_RUN=1 to stop before committing/pushing, and BICING_UPDATE_ARGS for
# extra options, e.g. BICING_UPDATE_ARGS="--months 6".
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
WT="$REPO/.update-worktree"
PY="$REPO/.venv/bin/python3"
export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$PATH"

log() { echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*"; }
notify() {
  log "$1"
  command -v osascript >/dev/null && osascript -e "display notification \"$1\" with title \"Bicing dashboard\"" >/dev/null 2>&1 || true
}
fail() { notify "Update failed: $1 (see ~/Library/Logs/bicing-dashboard-update.log)"; exit 1; }

[ -x "$PY" ] || fail "Python environment missing; run scripts/macos/install_schedule.sh"
log "Starting in $REPO"

# 1. fresh worktree on the latest main
git -C "$REPO" fetch -q origin main || fail "git fetch failed (offline?)"
if [ ! -e "$WT/.git" ]; then
  git -C "$REPO" worktree prune
  git -C "$REPO" worktree add -q --detach "$WT" origin/main || fail "could not create worktree"
fi
git -C "$WT" checkout -q --detach origin/main && git -C "$WT" reset -q --hard origin/main && git -C "$WT" clean -qfd \
  || fail "could not reset worktree"

# 2. update the data
# shellcheck disable=SC2086
"$PY" "$WT/scripts/bicing_data.py" update ${BICING_UPDATE_ARGS:-}
rc=$?
if [ $rc -eq 2 ]; then
  fail "some months could not be downloaded"
elif [ $rc -ne 0 ]; then
  fail "update script exited with $rc"
fi

if [ -z "$(git -C "$WT" status --porcelain)" ]; then
  log "Data is up to date; nothing to do."
  exit 0
fi

# 3. one branch per set of months, so weekly runs don't open duplicate PRs
MONTHS="$("$PY" -c "import json,sys; print('_'.join(json.load(open(sys.argv[1]))['months']))" "$WT/data/meta.json")"
BRANCH="data-update/${MONTHS:-$(date +%Y-%m-%d)}"
if git -C "$REPO" ls-remote --exit-code --heads origin "$BRANCH" >/dev/null 2>&1; then
  log "Branch $BRANCH already exists on GitHub (waiting for review/merge); nothing to do."
  exit 0
fi
if [ "${DRY_RUN:-0}" = "1" ]; then
  log "DRY_RUN=1: would commit to $BRANCH"; git -C "$WT" status --short; exit 0
fi

git -C "$WT" checkout -q -b "$BRANCH" || fail "could not create branch $BRANCH"
git -C "$WT" add -A data
git -C "$WT" commit -q -m "Update Bicing data: ${MONTHS//_/, }" -m "Generated by scripts/macos/weekly_update.sh" \
  || fail "commit failed"
git -C "$WT" push -q -u origin "$BRANCH" || fail "push failed"

TITLE="Update Bicing data: ${MONTHS//_/, }"
if command -v gh >/dev/null && gh auth status >/dev/null 2>&1; then
  URL="$(cd "$WT" && gh pr create --base main --head "$BRANCH" --title "$TITLE" \
    --body "Automatic weekly data update: the latest complete months from Barcelona Open Data (${MONTHS//_/, }).")" \
    || fail "pull request could not be created"
  notify "New data ready for review: $URL"
  command -v open >/dev/null && open "$URL"
else
  REMOTE="$(git -C "$REPO" remote get-url origin | sed -E 's#(git@github.com:|https://github.com/)##; s#\.git$##')"
  notify "New data pushed to $BRANCH. Open a pull request on GitHub."
  command -v open >/dev/null && open "https://github.com/$REMOTE/compare/main...$BRANCH?expand=1"
fi
